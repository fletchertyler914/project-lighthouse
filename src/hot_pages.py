#!/usr/bin/env python3
"""
hot_pages.py - the swarm's work list: every deep-read page with surprise >= threshold that is not yet
mentioned in the ledger, newest-highest first. Writes docs/HOT_PAGES.md. Pure data processing; run with -I.

    python3 -I src/hot_pages.py [--min 5]
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MIN = int(sys.argv[sys.argv.index("--min") + 1]) if "--min" in sys.argv else 5


def main():
    ledger = (ROOT / "ledger" / "LEADS.md").read_text(encoding="utf-8")
    rows = []
    for ddir in sorted(ROOT.glob("data/*/deep")):
        author = ddir.parent.name
        for f in ddir.glob("*.json"):
            try:
                rec = json.loads(f.read_text(encoding="utf-8"))
            except Exception:  # noqa: BLE001
                continue
            d = rec.get("deep") or {}
            s = d.get("surprise")
            if not isinstance(s, (int, float)) or s < MIN:
                continue
            bundle = rec.get("bundle") or rec.get("cote") or f.stem.split("_")[0]
            page = rec.get("page") or f.stem.split("_", 1)[-1]
            label = rec.get("label") or page
            # "mentioned" = the bundle name and the page label/stem both occur in the ledger
            seen = bundle in ledger and (str(label) in ledger or str(page) in ledger)
            reason = (d.get("surprise_reason") or d.get("reason") or "").replace("\n", " ")[:220]
            res = d.get("results") or d.get("ideas") or []
            names = "; ".join(str((r.get("modern_name") or r.get("what") or ""))[:60] for r in res[:3] if isinstance(r, dict))
            rows.append((s, author, bundle, label, page, rec.get("image", ""), reason, names, seen))
    rows.sort(key=lambda r: (-r[0], r[1], r[2], str(r[4])))
    out = [f"# Hot pages (surprise ≥ {MIN}, model-rated, unreviewed unless marked)\n",
           "Generated by `src/hot_pages.py`. Pick one, read the scan yourself, check the author's own works and older",
           "sources, then either add a one-line 'Dropped' entry to the ledger or open a candidate. ✔ = already in ledger.\n",
           "| s | author | bundle | page | scan | model's reason | modern names | |", "|---|---|---|---|---|---|---|---|"]
    for s, a, b, lab, pg, img, reason, names, seen in rows:
        link = f"[scan]({img})" if img else ""
        out.append(f"| {s} | {a} | {b} | {lab} | {link} | {reason} | {names} | {'✔' if seen else ''} |")
    (ROOT / "docs" / "HOT_PAGES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    n_open = sum(1 for r in rows if not r[8])
    print(f"{len(rows)} pages with surprise >= {MIN}; {n_open} not yet in the ledger -> docs/HOT_PAGES.md")


if __name__ == "__main__":
    main()
